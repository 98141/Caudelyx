/* Browser walk for S06-P03 against this package's own Mongo group. Not an economic unit mock. */
import { writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { p03Profile } from './p03-profile.mjs';
import { setup } from '../../../servidor/dist-s06/tests/s06/fixture.js';
const { generate } = await import(pathToFileURL(resolve(dirname(fileURLToPath(import.meta.url)), '../../../servidor/node_modules/otplib/dist/index.js')).href);

const here = dirname(fileURLToPath(import.meta.url));
const evidence = resolve(here, '../../../../Construccion/Sprints/S06/Evidencias');
const { chromium } = await import(pathToFileURL(resolve(here, '../../node_modules/playwright/index.mjs')).href);
const started = Date.now();
const steps = [];
const traces = [];
function mark(name, extra = {}) { steps.push({ name, at: new Date().toISOString(), ...extra }); }

const group = await p03Profile();
let browser;
try {
  mark('group-ready');
  const f = await setup(group);
  mark('seed-organization');
  const bank = await f.accountS06('BANK_UI', 'ASSET', 'BANK');
  await f.heldProfile();
  const loan = await f.loan({ principal: '2000000.00' });
  await f.disburse(loan);
  const approver = await f.member('P');
  mark('seed-loan', { organization: f.org });
  const https = await f.https(true);
  const origin = 'https://localhost:' + https.port;
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1280, height: 800 } });
  let page;
  await context.addCookies([{ name: '__Host-caudelyx-session', value: f.a.issued.token, url: origin + '/', secure: true, httpOnly: true, sameSite: 'Lax' }]);
  page = await context.newPage();
  const titularPage = page;
  await page.clock.install({ time: new Date('2026-10-31T17:00:00Z') });
  await page.goto(origin + '/#/pagos', { waitUntil: 'domcontentloaded' });
  await page.getByRole('heading', { name: 'Pagos' }).waitFor();
  const checkbox = page.getByRole('checkbox').first();
  await checkbox.waitFor();
  await checkbox.check();
  const target = page.getByLabel(/^Importe para /).first();
  await target.fill('100000');
  await page.getByLabel('Importe del recibo').fill('100000');
  await page.getByLabel('Referencia').fill('REC-CAMINATA');
  await page.getByLabel('Soporte').fill('SOP-CAMINATA');
  await page.getByRole('button', { name: 'Pedir el plan' }).click();
  await page.getByText('Plan sin efecto.').waitFor();
  await page.getByRole('checkbox', { name: /Confirmo este plan del servidor/ }).check();
  await page.getByRole('button', { name: 'Confirmar el registro' }).click();
  await page.getByText('El servidor confirmó el comando. Esto no habilita un cobro real.').waitFor();
  await page.getByText('Transferencia. No crea custodia de cobrador ni concilia el banco por este registro.').waitFor();
  mark('registered-pending');
  await page.screenshot({ path: resolve(evidence, 'S06-P03-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 360, height: 780 });
  await page.screenshot({ path: resolve(evidence, 'S06-P03-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1280, height: 800 });
  mark('screenshots');
  const approverContext = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1280, height: 800 } });
  await approverContext.addCookies([{ name: '__Host-caudelyx-session', value: approver.issued.token, url: origin + '/', secure: true, httpOnly: true, sameSite: 'Lax' }]);
  const approverPage = await approverContext.newPage();
  page = approverPage;
  await approverPage.clock.install({ time: new Date('2026-10-31T17:00:00Z') });
  await approverPage.goto(origin + '/#/pagos', { waitUntil: 'domcontentloaded' });
  await approverPage.getByRole('heading', { name: 'Pagos' }).waitFor();
  await approverPage.getByRole('button', { name: /REC-CAMINATA/ }).click();
  await approverPage.getByRole('button', { name: 'Pedir el plan de aprobación' }).click();
  await page.getByRole('checkbox', { name: /Confirmo este plan del servidor/ }).check();
  await page.getByRole('button', { name: 'Confirmar la aprobación' }).click();
  await page.getByLabel('Código de 6 dígitos').waitFor();
  f.clock.value += 30000;
  const code = await generate({ secret: approver.secret, epoch: Math.floor(f.now() / 1000) });
  await page.getByLabel('Código de 6 dígitos').fill(code);
  await page.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await page.getByText('El servidor confirmó el comando. Esto no habilita un cobro real.').waitFor();
  mark('approved');
  page = titularPage;
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('heading', { name: 'Pagos' }).waitFor();
  await page.getByRole('button', { name: /REC-CAMINATA/ }).click();
  await page.getByRole('columnheader', { name: 'Número' }).waitFor();
  await page.locator('p').filter({ hasText: 'Pendiente de conciliar' }).waitFor();
  await page.getByRole('combobox', { name: 'Cuenta bancaria de la organización', exact: true }).fill('BANK');
  await page.getByRole('option', { name: /BANK_UI/ }).click();
  await page.getByRole('combobox', { name: 'Cuenta bancaria de la organización', exact: true }).filter({ hasText: 'BANK_UI' }).waitFor().catch(() => undefined);
  await page.getByLabel('Importe declarado').fill('100000');
  await page.getByLabel('Fecha del movimiento').fill('2026-10-31');
  await page.getByLabel('Referencia declarada').fill('REC-CAMINATA');
  await page.getByLabel('Referencia del extracto').fill('EXT-1');
  await page.getByLabel('Línea declarada').fill('1');
  await page.getByLabel('Nombre declarado del banco').fill('Banco sintético');
  const declared = page.waitForResponse(response => response.url().includes('/bank-declarations') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Declarar el movimiento' }).click();
  const declaredResponse = await declared;
  if (declaredResponse.status() !== 201) throw new Error('La declaración respondió ' + declaredResponse.status() + ' ' + (await declaredResponse.text()).slice(0, 240));
  const declaration = page.locator('option', { hasText: 'REC-CAMINATA' });
  await declaration.waitFor({ state: 'attached' });
  await page.getByLabel('Declaración para vincular').selectOption(await declaration.getAttribute('value'));
  const linked = page.waitForResponse(response => response.url().includes('/reconciliation-links') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Vincular uno a uno' }).click();
  const linkedResponse = await linked;
  if (linkedResponse.status() !== 201) throw new Error('El vínculo respondió ' + linkedResponse.status() + ' ' + (await linkedResponse.text()).slice(0, 240));
  mark('reconciled');
  await page.getByLabel('Motivo del reverso').fill('Corrección sintética');
  const reversal = page.waitForResponse(response => response.url().includes('/reversal-requests') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Solicitar la compensación' }).click();
  const reversalResponse = await reversal;
  if (reversalResponse.status() !== 201) throw new Error('La solicitud de reverso respondió ' + reversalResponse.status() + ' ' + (await reversalResponse.text()).slice(0, 240));
  mark('reversal-requested');
  await writeFile(resolve(evidence, 'S06-P03-WALK.json'), JSON.stringify({ result: 'PASS', durationMs: Date.now() - started, steps, organization: f.org, httpsPort: https.port }, null, 2));
} catch (error) {
  let pageText = '';
  try { pageText = (await page?.locator('main, body').first().innerText())?.slice(0, 1800) ?? ''; } catch { /* page may already be closed */ }
  try { await page?.screenshot({ path: resolve(evidence, 'S06-P03-FAIL.png'), fullPage: true }); } catch { /* no page */ }
  mark('failed', { reason: String(error).slice(0, 500) });
  await writeFile(resolve(evidence, 'S06-P03-WALK.json'), JSON.stringify({ result: 'FAIL', durationMs: Date.now() - started, steps, reason: String(error).slice(0, 800), pageText, traces }, null, 2));
  throw error;
} finally {
  await browser?.close();
  await group.dispose();
}
